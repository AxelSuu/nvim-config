-- Space EG: GitHub Actions workflow that builds the project for its chip on every push and pull
-- request (espressif/esp-idf-ci-action, official ESP-IDF Docker image) and keeps the firmware
local util = require("esp.util")
local M = {}

function M.write_workflow()
  local root = util.project_root()
  if not vim.uv.fs_stat(root .. "/CMakeLists.txt") then
    return vim.notify("Not an ESP-IDF project: " .. root, vim.log.levels.ERROR)
  end
  local repo = vim.fs.root(root, ".git") or root
  local sub = root == repo and "" or root:sub(#repo + 2)
  local name = vim.fs.basename(root)
  local target = util.sdkconfig_target(root)
  local install = util.install()
  local version = install and install.version or "latest"
  local dir = repo .. "/.github/workflows"
  local path = ("%s/esp-idf-%s.yml"):format(dir, name)
  local build = sub == "" and "build" or (sub .. "/build")
  local lines = {
    "# Generated by Neovim (Space EG): builds "
      .. name
      .. " for "
      .. target
      .. " with ESP-IDF "
      .. version,
    "name: ESP-IDF build (" .. name .. ")",
    "",
    "on:",
    "  push:",
    "  pull_request:",
    "",
    "jobs:",
    "  build:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - uses: actions/checkout@v4",
    "        with:",
    "          submodules: recursive",
    "      - uses: espressif/esp-idf-ci-action@v1",
    "        with:",
    "          esp_idf_version: " .. version,
    "          target: " .. target,
    "          path: '" .. sub .. "'",
    "          command: idf.py build && idf.py size",
    "      - uses: actions/upload-artifact@v4",
    "        with:",
    "          name: " .. name .. "-" .. target .. "-firmware",
    "          path: |",
    "            " .. build .. "/*.bin",
    "            " .. build .. "/*.elf",
    "            " .. build .. "/bootloader/bootloader.bin",
    "            " .. build .. "/partition_table/partition-table.bin",
    "            " .. build .. "/flash_args",
  }
  vim.fn.mkdir(dir, "p")
  vim.fn.writefile(lines, path)
  vim.cmd.edit(path)
  local hint = vim.uv.fs_stat(repo .. "/.git") and "commit and push to run it"
    or "the project is not a git repo yet: git init, commit, push to GitHub"
  vim.notify("Wrote " .. path:sub(#repo + 2) .. " (" .. hint .. ")")
end

return M
